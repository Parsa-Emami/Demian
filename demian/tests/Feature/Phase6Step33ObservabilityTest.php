    public function test_public_telemetry_is_opt_in_rejected_by_default_and_public_health_stays_minimal(): void
    {
        config()->set('demian-ops.enabled', false);
        $this->postJson('/api/v1/arcade/telemetry', [
            'kind' => 'game_load', 'game' => 'open-world', 'duration_ms' => 1200,
        ])->assertNotFound();

        $health = $this->getJson('/api/v1/arcade/health')->assertOk()->json();
        $this->assertArrayHasKey('status', $health);
        $this->assertArrayNotHasKey('db_host', $health);
        $this->assertArrayNotHasKey('log_directory', $health);
        $this->getJson('/api/v1/arcade/ops')->assertNotFound();
    }

    public function test_telemetry_strictly_emits_allowlisted_dimensions_without_bearer_or_input(): void
    {
        $this->withoutMiddleware(ThrottleRequests::class);
        config()->set('demian-ops.enabled', true);
        config()->set('demian-ops.client_telemetry_enabled', true);
        config()->set('demian-ops.sample_rate', 1);
        $rows = (object) ['logs' => []];
        $logger = new class($rows)
        {
            public function __construct(private object $sink) {}
            public function info(string $event, array $context): void
            {
                $this->sink->logs[] = [$event, $context];
            }
        };
        Log::shouldReceive('channel')->with('demian_ops')->andReturn($logger);

        $this->postJson('/api/v1/arcade/telemetry', [
            'kind' => 'game_load', 'game' => 'open-world', 'duration_ms' => 900,
            'message' => 'secret-info', 'token' => 'secret-info', 'user_id' => 'secret-info',
        ])->assertStatus(202)->assertJsonPath('status', 'accepted');
        $this->assertNotEmpty($rows->logs);
        $client = array_values(array_filter($rows->logs, fn (array $entry): bool =>
            $entry[0] === 'client_metric'));
        $this->assertCount(1, $client);
        $this->assertSame([
            'event' => 'client', 'kind' => 'game_load', 'game' => 'open-world',
            'duration_ms' => 900, 'fps' => null,
        ], $client[0][1]);
        $this->assertStringNotContainsString('secret-info',
            json_encode($rows->logs, JSON_THROW_ON_ERROR));
        // Correlation ID is generated by the server, never accepted from input.
        $http = array_values(array_filter($rows->logs, fn (array $entry): bool =>
            $entry[0] === 'api_request'));
        $this->assertCount(1, $http);
        $this->assertSame('telemetry', $http[0][1]['route_group']);
        $this->assertSame(202, $http[0][1]['status']);
        $this->assertMatchesRegularExpression('/^[a-f0-9]{24}$/', $http[0][1]['request_id']);
    }

    public function test_invalid_telemetry_is_rejected_and_not_logged_as_client_metric(): void
    {
        $this->withoutMiddleware(ThrottleRequests::class);
        config()->set('demian-ops.enabled', true);
        config()->set('demian-ops.client_telemetry_enabled', true);
        $this->postJson('/api/v1/arcade/telemetry',
            ['kind' => 'game_load', 'game' => 'unknown', 'duration_ms' => 30])
            ->assertUnprocessable();
        $this->postJson('/api/v1/arcade/telemetry',
            ['kind' => 'game_load', 'duration_ms' => 30])
            ->assertUnprocessable();
        $this->postJson('/api/v1/arcade/telemetry',
            ['kind' => 'fps', 'fps' => 400])->assertUnprocessable();
        $this->postJson('/api/v1/arcade/telemetry',
            ['kind' => 'arbitrary'])->assertUnprocessable();
    }

    public function test_aggregations_use_bounded_samples_and_explicit_insufficient_data(): void
    {
        $empty = OpsReport::aggregate([]);
        $this->assertSame(0, $empty['http_samples']);
        $this->assertNull($empty['http_p95_ms']);
        $this->assertNull($empty['game_load_p95_ms']);
        $this->assertSame(0, $empty['estimated_requests']);

        $input = [
            ['event' => 'http', 'status' => 200, 'duration_ms' => 20,
                'sample_weight' => 5, 'route_group' => 'leaderboard', 'slow' => false],
            ['event' => 'http', 'status' => 500, 'duration_ms' => 1200,
                'sample_weight' => 1, 'route_group' => 'run_complete', 'slow' => true],
            ['event' => 'http', 'status' => 422, 'duration_ms' => 100,
                'sample_weight' => 1, 'route_group' => 'account', 'slow' => false],
            ['event' => 'client', 'kind' => 'game_load', 'game' => 'open-world', 'duration_ms' => 7000],
            ['event' => 'client', 'kind' => 'game_error', 'game' => 'dino-run'],
            ['event' => 'client', 'kind' => 'fps', 'fps' => 28],
            ['event' => 'http', 'status' => 200, 'duration_ms' => 90,
                'sample_weight' => 99999, 'route_group' => '../../../escape', 'slow' => false],
        ];
        $aggregate = OpsReport::aggregate($input);
        $this->assertSame(4, $aggregate['http_samples']);
        $this->assertEquals(107, $aggregate['estimated_requests']); // per-entry weight <= 100
        $this->assertSame(1200, $aggregate['http_p95_ms']);
        $this->assertSame(1, $aggregate['http_5xx']);
        $this->assertSame(1, $aggregate['http_4xx']);
        $this->assertSame(1, $aggregate['slow_samples']);
        $this->assertSame(1, $aggregate['game_errors']);
        $this->assertSame(28, $aggregate['fps_p10']);
        $this->assertSame(['account' => 1, 'leaderboard' => 1,
            'other' => 1, 'run_complete' => 1], $aggregate['route_groups']);
    }

    public function test_private_report_reads_only_capped_json_metrics_and_checks_cron(): void
    {
        config()->set('demian-ops.enabled', true);
        config()->set('demian-ops.disk_min_free_bytes', 1);
        config()->set('demian-ops.minimum_http_samples', 10);
        Cache::put(OpsReport::HEARTBEAT, now()->timestamp, now()->addMinutes(20));
        $report = app(OpsReport::class)->snapshot();
        $this->assertSame(true, $report['enabled']);
        $this->assertSame('ok', $report['status']);
        $this->assertSame([], $report['alerts']);
        $this->assertSame([], array_filter($report['checks'], fn ($v) => ! $v['passed']));
        Cache::put(OpsReport::HEARTBEAT, now()->subHour()->timestamp, now()->addMinutes(20));
        $stale = app(OpsReport::class)->snapshot();
        $this->assertContains('cron_stale', $stale['alerts']);
        $this->assertSame('degraded', $stale['status']);
    }

    public function test_alerts_are_deduplicated_and_disabled_monitor_never_sends_anything(): void
    {
        $dispatcher = app(OpsAlertDispatcher::class);
        config()->set('demian-ops.alert_email', '');
        $report = ['enabled' => true, 'alerts' => ['disk_low', 'disk_low', 'not_approved']];
        Cache::forget('demian:ops:alert:v1:disk_low');
        $this->assertSame(['disk_low'], $dispatcher->dispatch($report));
        $this->assertSame([], $dispatcher->dispatch($report));
        $this->assertSame([], $dispatcher->dispatch(['enabled' => false, 'alerts' => ['disk_low']]));
    }

    public function test_operations_dashboard_is_not_public_and_admin_cannot_view_superadmin_metrics(): void
    {
        config()->set('demian-coupons.cafe_enabled', true);
        config()->set('demian-ops.enabled', false);
        $this->get('/cashier/admin/observability')->assertRedirect(route('cashier.login'));
        foreach (['admin', 'super_admin'] as $role) {
            $id = DB::table('arcade_cashier_staff')->insertGetId([
                'username' => Str::lower(Str::random(12)),
                'display_name' => 'Operator', 'password_hash' => Hash::make('SecurePassword#2026'),
                'branch_id' => 'cafe-main', 'role' => $role, 'is_active' => true,
                'session_version' => 1, 'created_at' => now(), 'updated_at' => now(),
            ]);
            $this->withSession([
                'cafe_staff_id' => $id, 'cafe_staff_version' => 1,
                'cafe_authenticated_at' => now()->timestamp,
            ]);
            if ($role === 'admin') $this->get('/cashier/admin/observability')->assertForbidden();
            else $this->get('/cashier/admin/observability')->assertOk()
                ->assertHeader('Cache-Control', 'private, no-store, max-age=0')
                ->assertSee('داشبورد مانیتورینگ دمیان');
        }
    }
}
